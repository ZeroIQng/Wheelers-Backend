#!/usr/bin/env node
/**
 * Register the WhatsApp AUTHENTICATION template that carries Wheelers
 * sign-in codes, straight through Meta's Graph API.
 *
 *   node scripts/meta-otp-template.mjs status   → WABA id, existing templates + approval status
 *   node scripts/meta-otp-template.mjs create   → create `wheelers_login_code` (idempotent) and wait for approval
 *
 * Reads META_ACCESS_TOKEN, META_PHONE_NUMBER_ID and (optionally) META_WABA_ID
 * from .env. When META_WABA_ID is missing, the WhatsApp Business Account is
 * discovered from the token. Meta fixes the wording of authentication
 * templates; the code itself is generated by our gateway and injected at send
 * time. Approval for this category is normally instant.
 */
import { readFileSync } from 'node:fs';

const env = Object.fromEntries(
  readFileSync(new URL('../.env', import.meta.url), 'utf8')
    .split(/\r?\n/)
    .filter((line) => line && !line.startsWith('#') && line.includes('='))
    .map((line) => {
      const i = line.indexOf('=');
      return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^['"]|['"]$/g, '')];
    }),
);

const TOKEN = env.META_ACCESS_TOKEN;
const PHONE_NUMBER_ID = env.META_PHONE_NUMBER_ID;
const GRAPH = 'https://graph.facebook.com/v21.0';
const TEMPLATE_NAME = env.META_OTP_TEMPLATE_NAME || 'wheelers_login_code';
const LANGUAGE = env.META_OTP_TEMPLATE_LANGUAGE || 'en_US';

if (!TOKEN || !PHONE_NUMBER_ID) {
  console.error('META_ACCESS_TOKEN and META_PHONE_NUMBER_ID must be set in .env');
  process.exit(1);
}

async function graph(path, init = {}) {
  const res = await fetch(`${GRAPH}${path}`, {
    ...init,
    headers: { authorization: `Bearer ${TOKEN}`, 'content-type': 'application/json', ...(init.headers ?? {}) },
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    const err = body?.error ?? {};
    throw new Error(`Meta ${res.status} on ${path}: ${err.message ?? JSON.stringify(body)}${err.error_user_msg ? ` — ${err.error_user_msg}` : ''}`);
  }
  return body;
}

async function findWabaId() {
  if (env.META_WABA_ID) return env.META_WABA_ID;

  // The token's granted scopes name the business accounts it can manage.
  const debug = await graph(`/debug_token?input_token=${encodeURIComponent(TOKEN)}`).catch(() => null);
  const scopes = debug?.data?.granular_scopes ?? [];
  const candidates = new Set();
  for (const scope of scopes) {
    if (scope.scope === 'whatsapp_business_management' || scope.scope === 'whatsapp_business_messaging') {
      for (const id of scope.target_ids ?? []) candidates.add(id);
    }
  }

  // A WhatsApp Flow knows its parent account even when the token's scopes do not.
  for (const key of ['WHATSAPP_FLOW_ID', 'WHATSAPP_RIDE_SEARCH_FLOW_ID', 'WHATSAPP_DRIVER_PROFILE_FLOW_ID']) {
    if (!env[key]) continue;
    const flow = await graph(`/${env[key]}?fields=whatsapp_business_account`).catch(() => null);
    if (flow?.whatsapp_business_account?.id) return flow.whatsapp_business_account.id;
  }

  // Keep only the account that owns our phone number.
  for (const id of candidates) {
    const phones = await graph(`/${id}/phone_numbers?fields=id,display_phone_number`).catch(() => null);
    if (phones?.data?.some((p) => p.id === PHONE_NUMBER_ID)) return id;
  }
  if (candidates.size === 1) return [...candidates][0];

  throw new Error(
    'Could not discover the WhatsApp Business Account id from the token. Add META_WABA_ID=<id> to .env (WhatsApp Manager → Business settings → WhatsApp accounts).',
  );
}

async function listTemplates(wabaId) {
  const res = await graph(`/${wabaId}/message_templates?fields=id,name,status,category,language,rejected_reason&limit=100`);
  return res.data ?? [];
}

async function status() {
  const wabaId = await findWabaId();
  const phone = await graph(`/${PHONE_NUMBER_ID}?fields=display_phone_number,verified_name,quality_rating`);
  console.log(`WABA id:         ${wabaId}`);
  console.log(`Phone:           ${phone.display_phone_number} (${phone.verified_name ?? 'unverified name'}, quality ${phone.quality_rating ?? 'n/a'})`);
  const templates = await listTemplates(wabaId);
  console.log(`Templates (${templates.length}):`);
  for (const t of templates) {
    console.log(`  ${t.name} [${t.language}] ${t.category} → ${t.status}${t.rejected_reason && t.rejected_reason !== 'NONE' ? ` (${t.rejected_reason})` : ''}`);
  }
  const ours = templates.find((t) => t.name === TEMPLATE_NAME && t.language === LANGUAGE);
  console.log(ours ? `\n${TEMPLATE_NAME} is ${ours.status}.` : `\n${TEMPLATE_NAME} not registered yet — run: node scripts/meta-otp-template.mjs create`);
}

async function create() {
  const wabaId = await findWabaId();
  const existing = (await listTemplates(wabaId)).find((t) => t.name === TEMPLATE_NAME && t.language === LANGUAGE);
  if (existing) {
    console.log(`${TEMPLATE_NAME} already exists (${existing.status}).`);
    if (existing.status === 'APPROVED') return printEnv();
    if (existing.status === 'REJECTED') {
      throw new Error(`Template was rejected (${existing.rejected_reason}). Delete it in WhatsApp Manager or pick another META_OTP_TEMPLATE_NAME.`);
    }
  } else {
    const created = await graph(`/${wabaId}/message_templates`, {
      method: 'POST',
      body: JSON.stringify({
        name: TEMPLATE_NAME,
        language: LANGUAGE,
        category: 'AUTHENTICATION',
        components: [
          { type: 'BODY', add_security_recommendation: true },
          { type: 'FOOTER', code_expiration_minutes: 5 },
          { type: 'BUTTONS', buttons: [{ type: 'OTP', otp_type: 'COPY_CODE', text: 'Copy code' }] },
        ],
      }),
    });
    console.log(`Created ${TEMPLATE_NAME} (id ${created.id}) — status ${created.status}.`);
    if (created.status === 'APPROVED') return printEnv();
  }

  process.stdout.write('Waiting for Meta approval');
  for (let i = 0; i < 24; i += 1) {
    await new Promise((r) => setTimeout(r, 5000));
    const now = (await listTemplates(wabaId)).find((t) => t.name === TEMPLATE_NAME && t.language === LANGUAGE);
    process.stdout.write('.');
    if (now?.status === 'APPROVED') {
      console.log(' approved.');
      return printEnv();
    }
    if (now?.status === 'REJECTED') throw new Error(`\nRejected: ${now.rejected_reason}`);
  }
  console.log('\nStill pending — check again later with: node scripts/meta-otp-template.mjs status');
}

function printEnv() {
  console.log('\nAdd to .env on the server, then `pm2 restart api-gateway --update-env`:');
  console.log(`META_OTP_TEMPLATE_NAME=${TEMPLATE_NAME}`);
  console.log(`META_OTP_TEMPLATE_LANGUAGE=${LANGUAGE}`);
}

const mode = process.argv[2];
try {
  if (mode === 'status') await status();
  else if (mode === 'create') await create();
  else {
    console.error('usage: node scripts/meta-otp-template.mjs <status|create>');
    process.exit(2);
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
